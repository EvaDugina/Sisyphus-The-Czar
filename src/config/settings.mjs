export function settingsGroupControls(group) {
  return [
    ...(Array.isArray(group.controls) ? group.controls : []),
    ...(Array.isArray(group.subgroups)
      ? group.subgroups.flatMap(settingsGroupControls)
      : []),
  ];
}

